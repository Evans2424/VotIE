#!/usr/bin/env python3
"""
dataset_analysis_and_convert.py

- Scans `data/ner_datasets` for `.jsonl` NER files.
- For each JSONL file it:
  - Computes dataset statistics (documents/minutes, segments, tokens, entity counts, per-municipality counts)
  - Writes a CoNLL-style file next to the JSONL file with the same base name and `.conll` extension
- Produces a human-readable report at `data/dataset_report.md` with per-file and aggregated statistics.

Usage:
  python data/dataset_analysis_and_convert.py
  python data/dataset_analysis_and_convert.py --input data/ner_datasets/pt/full_dataset_pt_ner.jsonl

This script uses only the Python standard library.
"""

import argparse
import json
import os
from collections import Counter, defaultdict
from pathlib import Path
import textwrap
import sys


def process_jsonl_file(path: Path, write_conll: bool = True):
    """Process a single JSONL file. Returns statistics dict and writes a .conll file if requested."""
    stats = {
        'file': str(path),
        'segments': 0,
        'tokens': 0,
        'unique_minutes': set(),
        'entity_counts': Counter(),
        'municipality_counts': Counter(),
    }

    conll_path = path.with_suffix('.conll')
    if write_conll:
        conll_f = conll_path.open('w', encoding='utf-8')
    else:
        conll_f = None

    with path.open('r', encoding='utf-8') as f:
        for line_no, line in enumerate(f, start=1):
            line = line.strip()
            if not line:
                continue
            try:
                item = json.loads(line)
            except json.JSONDecodeError:
                print(f"JSON decode error in {path} line {line_no}", file=sys.stderr)
                continue
            stats['segments'] += 1
            tokens = item.get('tokens', [])
            labels = item.get('labels', [])
            stats['tokens'] += len(tokens)
            mid = item.get('id', '')
            if mid:
                # assume segments split with suffix like _1, _2 etc.
                base = mid.rsplit('_', 1)[0]
                stats['unique_minutes'].add(base)
            mun = item.get('municipality_id')
            if mun:
                stats['municipality_counts'][mun] += 1

            if len(tokens) != len(labels):
                print(f"Warning: token/label length mismatch in {path}, line {line_no} (tokens={len(tokens)}, labels={len(labels)})", file=sys.stderr)

            # count entities using BIO scheme
            i = 0
            while i < len(labels):
                lab = labels[i]
                if isinstance(lab, str) and lab.startswith('B-'):
                    ent_type = lab[2:]
                    stats['entity_counts'][ent_type] += 1
                    i += 1
                    while i < len(labels) and isinstance(labels[i], str) and labels[i].startswith('I-'):
                        i += 1
                    continue
                i += 1

            # write conll: token TAB label per line, blank line between segments
            if conll_f is not None:
                for t, l in zip(tokens, labels):
                    # replace newlines/tabs in tokens
                    safe_t = t.replace('\n', ' ').replace('\t', ' ')
                    conll_f.write(f"{safe_t}\t{l}\n")
                conll_f.write("\n")

    if conll_f is not None:
        conll_f.close()

    # finalize stats
    stats['unique_minutes'] = len(stats['unique_minutes'])
    stats['total_entities'] = sum(stats['entity_counts'].values())
    stats['avg_tokens_per_segment'] = stats['tokens'] / stats['segments'] if stats['segments'] else 0

    return stats, conll_path if write_conll else None


def scan_and_process(root: Path, write_conll: bool = True):
    jsonl_paths = list(root.rglob('*.jsonl'))
    results = []
    for p in sorted(jsonl_paths):
        stats, conll_path = process_jsonl_file(p, write_conll=write_conll)
        stats['conll_written'] = str(conll_path) if conll_path else None
        results.append(stats)
    return results


def format_report(results, out_path: Path):
    lines = []
    lines.append('# Dataset analysis report')
    lines.append('')
    lines.append('This report was generated by `data/dataset_analysis_and_convert.py`. It summarizes per-file and aggregated statistics for the NER JSONL datasets and lists the corresponding CoNLL files produced.')
    lines.append('')

    # per-file
    for s in results:
        lines.append(f"## File: {s['file']}")
        lines.append('')
        lines.append(f"- segments (JSONL lines): {s['segments']}")
        lines.append(f"- unique minutes/documents: {s['unique_minutes']}")
        lines.append(f"- tokens (total): {s['tokens']}")
        lines.append(f"- avg tokens / segment: {s['avg_tokens_per_segment']:.1f}")
        lines.append(f"- total entity mentions: {s['total_entities']}")
        lines.append(f"- CoNLL written to: {s.get('conll_written')}")
        lines.append('')
        # entities
        if s['total_entities']:
            lines.append('  - Entities by type:')
            for t, c in s['entity_counts'].most_common():
                pct = c / s['total_entities'] * 100 if s['total_entities'] else 0
                lines.append(f"    - {t}: {c} ({pct:.1f}%)")
            lines.append('')
        # municipalities
        if s['municipality_counts']:
            lines.append('  - Segments by municipality:')
            for m, c in s['municipality_counts'].most_common():
                lines.append(f"    - {m}: {c}")
            lines.append('')

    # aggregated overview
    agg = {
        'segments': 0,
        'tokens': 0,
        'unique_minutes': 0,  # can't easily aggregate unique minutes across files reliably; sum instead
        'entity_counts': Counter(),
        'municipality_counts': Counter(),
        'total_entities': 0,
    }
    for s in results:
        agg['segments'] += s['segments']
        agg['tokens'] += s['tokens']
        agg['unique_minutes'] += s['unique_minutes']
        agg['entity_counts'].update(s['entity_counts'])
        agg['municipality_counts'].update(s['municipality_counts'])
        agg['total_entities'] += s['total_entities']

    lines.append('---')
    lines.append('')
    lines.append('## Aggregated summary (all processed files)')
    lines.append('')
    lines.append(f"- files processed: {len(results)}")
    lines.append(f"- segments: {agg['segments']}")
    lines.append(f"- tokens: {agg['tokens']}")
    lines.append(f"- sum(unique_minutes per file): {agg['unique_minutes']} (note: a single minute may appear across files; see per-file counts for exact document counts)")
    lines.append(f"- total entities: {agg['total_entities']}")
    lines.append(f"- avg tokens / segment (aggregate): {agg['tokens']/agg['segments']:.1f}" if agg['segments'] else '-')
    lines.append('')
    if agg['total_entities']:
        lines.append('Entities (aggregate):')
        for t, c in agg['entity_counts'].most_common():
            lines.append(f"- {t}: {c} ({c/agg['total_entities']*100:.1f}%)")
        lines.append('')

    if agg['municipality_counts']:
        lines.append('Segments by municipality (aggregate):')
        for m, c in agg['municipality_counts'].most_common():
            lines.append(f"- {m}: {c}")
        lines.append('')

    out_path.write_text('\n'.join(lines), encoding='utf-8')
    return out_path


def main():
    parser = argparse.ArgumentParser(description='Analyze JSONL NER datasets and convert to CoNLL format')
    parser.add_argument('--input', type=str, default=None, help='Single JSONL file to process (optional). If omitted, all .jsonl under data/ner_datasets are processed.')
    parser.add_argument('--root', type=str, default='data/ner_datasets', help='Root directory to search for JSONL files (default: data/ner_datasets)')
    parser.add_argument('--no-conll', action='store_true', help='Do not write .conll files, only compute stats')
    parser.add_argument('--report', type=str, default='data/dataset_report.md', help='Output report path')
    args = parser.parse_args()

    root = Path(args.root)

    if args.input:
        p = Path(args.input)
        if not p.exists():
            print(f"Input file not found: {p}", file=sys.stderr)
            sys.exit(1)
        results = []
        stats, conll_path = process_jsonl_file(p, write_conll=not args.no_conll)
        stats['conll_written'] = str(conll_path) if conll_path else None
        results.append(stats)
    else:
        results = scan_and_process(root, write_conll=not args.no_conll)

    report_path = format_report(results, Path(args.report))
    print(f"Report written to: {report_path}")
    print("Processed files:")
    for r in results:
        print(f" - {r['file']}: segments={r['segments']}, tokens={r['tokens']}, entities={r['total_entities']}")


if __name__ == '__main__':
    main()
